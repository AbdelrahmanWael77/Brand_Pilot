// P1: lists every difference between the recorded FlowNest baseline (before P1) and what BrandPilot recommends now.
//   node scripts/flownest-diff.mjs   → writes docs/ui-audit/p1-baseline-diff.md (needs Google Chrome)
// Part A compares like with like (all imported data): what moving the rules to the server changed.
// Part B shows what the screens' default period (last 28 days) changes on top of that.
// Every difference must carry a reason (REASONS below); an unexplained one is printed as "NO REASON YET".
import fs from 'node:fs';
import { execSync } from 'node:child_process';
import { captureFlowNest } from '../ui-tests/lib/flownest.mjs';
import { REASONS, GENERAL } from './flownest-diff-reasons.mjs';

// The baseline recorded before P1 (checkpoint 1, commit fc8a772), read from Git so this diff stays reproducible after the re-record.
const BASE_REF = 'fc8a772';
const base = JSON.parse(execSync(`git show ${BASE_REF}:test/fixtures/flownest/baseline.json`, { cwd: new URL('..', import.meta.url), maxBuffer: 1 << 26 }).toString());
const cap = await captureFlowNest();
const FIELDS = ['kind', 'title', 'why', 'action', 'ev', 'conf'];
const show = (v) => (Array.isArray(v) ? v.join(' / ') : String(v ?? '—')).replace(/\|/g, '\\|').replace(/\n/g, ' ');
const reason = (part, id, field) => REASONS[`${part}:${id}:${field}`] ?? REASONS[`${part}:${id}:*`] ?? REASONS[`${part}:*:${field}`] ?? 'NO REASON YET';

function compare(part, oldList, newList) {
  const rows = [];
  const o = new Map(oldList.map((x, i) => [x.id, { ...x, rank: i + 1 }]));
  const n = new Map(newList.map((x, i) => [x.id, { ...x, rank: i + 1 }]));
  for (const id of new Set([...o.keys(), ...n.keys()])) {
    const a = o.get(id), b = n.get(id);
    if (!b) { rows.push([id, 'removed', '—', show(a.title), '—', reason(part, id, 'removed')]); continue; }
    if (!a) { rows.push([id, 'added', '—', '—', show(b.title), reason(part, id, 'added')]); continue; }
    for (const f of FIELDS) {
      if (JSON.stringify(a[f]) !== JSON.stringify(b[f])) rows.push([id, 'changed', f, show(a[f]), show(b[f]), reason(part, id, f) + (f === 'conf' && b.confidence ? ' Now: “' + b.confidence.why + '”' : '')]);
    }
    if (a.rank !== b.rank) rows.push([id, 'changed', 'position', String(a.rank), String(b.rank), reason(part, id, 'position')]);
  }
  return rows;
}
const table = (rows) => ['| Recommendation | Change | Field | Old value | New value | Reason |', '|---|---|---|---|---|---|', ...rows.map((r) => `| \`${r[0]}\` | ${r.slice(1).join(' | ')} |`)].join('\n');

const A = compare('A', base.recs.en, cap.recs.all.en);
const Aar = compare('A', base.recs.ar, cap.recs.all.ar).filter((r) => r[2] !== 'position'); // positions are the same as in English
const B = compare('B', cap.recs.all.en, cap.recs['28'].en);
const missing = [...A, ...Aar, ...B].filter((r) => r[5] === 'NO REASON YET').length;
const ids = (l) => l.map((x) => x.id).join(', ');
const md = `# P1 — FlowNest recommendations: baseline vs now

Generated by \`node scripts/flownest-diff.mjs\` on ${new Date().toISOString().slice(0, 10)}. Baseline: \`test/fixtures/flownest/baseline.json\`
(recorded ${base.recordedAt} at ${base.commit}, before P1: the browser computed the recommendations over **all imported data**).
Now: the server computes them (the only source since P1). Same synthetic FlowNest company, same steps, no AI.

${GENERAL}

## Counts

| | Before P1 (browser, all data) | Now (server, all data) | Now (server, last 28 days — the screens' default) |
|---|---|---|---|
| Recommendations listed | ${base.recs.en.length} | ${cap.recs.all.en.length} | ${cap.recs['28'].en.length} |
| Ids | ${ids(base.recs.en)} | ${ids(cap.recs.all.en)} | ${ids(cap.recs['28'].en)} |

## The 7 recommendations that were only in the browser

| Recommendation | Now on the server? |
|---|---|
${['offer-conflict', 'claims', 'know-gaps', 'pf-depth', 'cta-mix', 'pf-noout', 'pf-seg'].map((id) => { const x = cap.recs.all.en.find((r) => r.id === id); return `| \`${id}\` | ${x ? `yes — “${show(x.title)}”, confidence ${x.conf}` : 'NOT PRESENT'} |`; }).join('\n')}

## Part A — moving the rules to the server (both over all imported data, English)

${A.length ? table(A) : 'No differences.'}

### Part A in Arabic (the same comparison, Arabic wording)

${Aar.length ? table(Aar) : 'No differences.'}

## Part B — the screens' period (all data → last 28 days, both now, English)

${B.length ? table(B) : 'No differences.'}

${missing ? `**${missing} difference(s) still have no reason.**` : 'Every difference above has a reason.'}
`;
fs.writeFileSync(new URL('../docs/ui-audit/p1-baseline-diff.md', import.meta.url), md);
console.log(`written docs/ui-audit/p1-baseline-diff.md — part A ${A.length} rows, part B ${B.length} rows, without reason: ${missing}`);
